def fetch_document(url):
    req = urllib.request.Request(url, headers={"User-Agent": "ragentic-manifests-catalog"})
    with urllib.request.urlopen(req, timeout=60) as res:
        raw = res.read()
    try:
        return raw, json.loads(raw)
    except json.JSONDecodeError:
        try:
            import yaml
        except ImportError:
            die("this definition is YAML; `pip install pyyaml` first")
        return raw, yaml.safe_load(raw)


def cmd_new(args):
    app_id = args.id
    if not ID_RE.match(app_id):
        die("id must match [a-z0-9][a-z0-9._-]{0,127}")
    if (APPS / app_id).exists():
        die(f"apps/{app_id} already exists")
    raw, doc = fetch_document(args.openapi)
    info = doc.get("info") or {}
    endpoint = args.endpoint or next(
        (s.get("url") for s in doc.get("servers") or [] if str(s.get("url", "")).startswith("https://")), None
    )
    title = args.title or info.get("title") or app_id
    base = {"protocol": "openapi", "specification": {"document": doc}, "type": "app"}
    if endpoint:
        base["endpoint"] = endpoint
    payload = {
        "a2ui": {},
        "app": app_id,
        "graph": openapi_graph(app_id, doc),
        "kind": "bundle",
        "manifest": {
            "apiVersion": "ragentic.dev/v1",
            "kind": "ConnectorTemplate",
            "metadata": {"name": app_id},
            "spec": {"base": base, "category": "app", "connector": {}, "status": "draft", "title": title},
        },
        "protocol": "openapi",
        "provenance": {
            "fetched_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "license": info.get("license"),
            "origins": [{"format": "openapi", "url": args.openapi, "version": str(doc.get("openapi") or doc.get("swagger"))}],
            "sha256": hashlib.sha256(raw).hexdigest(),
            "source_id": app_id,
            "source_updated": None,
            "url": args.openapi,
        },
        "readiness": "discovered",
        "review_required": {
            "authentication": True,
            "branding": True,
            "connection_test": True,
            "external_references": [],
            "setup_guide": True,
            "source_currency": True,
        },
        "setup_verification": "not_live_verified",
        "version": str(info.get("version") or "1"),
    }
    if args.credential:
        payload["setup"] = {"credential": {"type": args.credential}}
        if args.header:
            payload["setup"]["credential"].update(header=args.header, prefix=args.prefix or "")
    listing = {"title": title, "catalog": "drafts"}
    signed, _ = signed_state()
    write_app(app_id, payload, listing, signed)
    (REPO / "CATALOG.md").write_text(render_catalog(signed))
    print(f"wrote apps/{app_id}/manifest.json and MANIFEST.md ({len(payload['graph']['nodes']) - 1} graph nodes)")
    print("next: review both files, run `python tools/catalog.py validate`, then open a pull request")


def cmd_graph(args):
    signed, _ = signed_state()
    for app_id in args.ids:
        payload, listing, _ = load_app(app_id)
        if payload.get("protocol") != "openapi":
            die(f"{app_id}: only OpenAPI graphs are generated; edit graph by hand for {payload.get('protocol')}")
        document = payload["manifest"]["spec"]["base"]["specification"]["document"]
        payload["graph"] = openapi_graph(app_id, document)
        write_app(app_id, payload, listing, signed)
        print(f"{app_id}: {len(payload['graph']['nodes'])} nodes")


def cmd_import(args):
    signed, _ = signed_state()
    for app_id, s in signed.items():
        entry = s["entry"]
        listing = {"title": entry["title"], "catalog": s["catalog"]}
        if entry.get("logo"):
            listing["logo"] = entry["logo"]
        write_app(app_id, s["payload"], listing, signed)
    (REPO / "CATALOG.md").write_text(render_catalog(signed))
    print(f"imported {len(signed)} applications into apps/")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("new", help="scaffold a draft application from an OpenAPI document")
    p.add_argument("id")
    p.add_argument("--openapi", required=True, help="URL of the OpenAPI or Swagger document (JSON or YAML)")
    p.add_argument("--title")
    p.add_argument("--endpoint", help="https base URL; defaults to the first https server in the document")
    p.add_argument("--credential", choices=["none", "static_bearer", "api_key_header"])
    p.add_argument("--header", help="header name for api_key_header")
    p.add_argument("--prefix", help="value prefix for api_key_header, e.g. Bearer")
    p.set_defaults(func=cmd_new)
    p = sub.add_parser("graph", help="regenerate OpenAPI operation graphs")
    p.add_argument("ids", nargs="+")
    p.set_defaults(func=cmd_graph)
    sub.add_parser("docs", help="regenerate MANIFEST.md bodies and CATALOG.md").set_defaults(func=cmd_docs)
    p = sub.add_parser("validate", help="check sources, signatures and generated docs")
    p.add_argument("--require-signed", action="store_true", help="also fail when anything is waiting for signature")
    p.set_defaults(func=cmd_validate)
    p = sub.add_parser("sign", help="sign pending changes with MANIFESTS_SIGNING_KEY")
    p.add_argument("--dry-run", action="store_true", help="show what would be signed without a key")
    p.set_defaults(func=cmd_sign)
    sub.add_parser("import", help="rebuild apps/ from the signed objects").set_defaults(func=cmd_import)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
