#!/usr/bin/env python3
"""Ragentic manifest catalog: plain-text sources, validation and signing.

Sources live in apps/<id>/manifest.json (the exact bundle payload, pretty-printed)
and apps/<id>/MANIFEST.md (a listing in front matter plus a generated, human-readable
body). The signed transport objects (index.json, browse-index.json, bundles/,
browse-bundles/ and sources.json) are produced from them by `sign`, with the
registry's Ed25519 root key and the ragentic.manifests/v1 domain prefix.

Commands:
  new <id> --openapi URL   scaffold a draft application from an OpenAPI document
  graph <id>...            regenerate an OpenAPI application's operation graph
  docs                     regenerate every MANIFEST.md body and CATALOG.md
  validate                 check sources, signatures and generated docs
  sign                     sign pending changes (needs MANIFESTS_SIGNING_KEY)
  import                   rebuild apps/ from the signed objects
"""

import argparse
import base64
import datetime
import hashlib
import json
import os
import re
import sys
import time
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APPS = REPO / "apps"
PREFIX = b"ragentic.manifests/v1\n"
MAX_PAYLOAD = 16_777_216
ID_RE = re.compile(r"\A[a-z0-9][a-z0-9._-]{0,127}\Z")
PROTOCOLS = ("openapi", "graphql", "asyncapi")
METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
NOT_CONNECTABLE = ("discovered", "preview_only")
# Catalog name in MANIFEST.md -> (index file, bundle directory, index kind)
CATALOGS = {
    "published": ("index.json", "bundles", "index"),
    "drafts": ("browse-index.json", "browse-bundles", "browse_index"),
}
GENERATED = (
    "<!-- Generated by tools/catalog.py from manifest.json. Edit the front matter "
    "above or manifest.json, then run `python tools/catalog.py docs`. -->"
)
SECRET_RE = re.compile(
    r"sk_live_[0-9A-Za-z]{16,}|gh[pousr]_[0-9A-Za-z]{30,}|xox[abpr]-[0-9A-Za-z-]{20,}"
    r"|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----"
)
SECRET_OK = re.compile(r"EXAMPLE|example|\.\.\.|…")


def die(msg):
    sys.exit(f"error: {msg}")


def b64d(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def b64e(b):
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def canonical(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def pretty(obj):
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def compact(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False)


def config():
    return json.loads((REPO / "registry.json").read_text())


def iso(ts):
    return datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


# --- Ed25519 -----------------------------------------------------------------


def _ed25519():
    try:
        from cryptography.hazmat.primitives.asymmetric import ed25519
    except ImportError:
        die("signature checks need `pip install cryptography`")
    return ed25519


def public_key():
    return _ed25519().Ed25519PublicKey.from_public_bytes(b64d(config()["root"]))


def open_envelope(env, key):
    """Return the payload bytes of an envelope signed by key, or raise ValueError."""
    from cryptography.exceptions import InvalidSignature

    data = b64d(env["payload"])
    try:
        key.verify(b64d(env["signature"]), PREFIX + data)
    except InvalidSignature:
        raise ValueError("bad signature")
    return data


def signing_key():
    raw = os.environ.get("MANIFESTS_SIGNING_KEY", "").strip()
    if not raw:
        die("MANIFESTS_SIGNING_KEY is not set")
    seed = bytes.fromhex(raw) if re.fullmatch(r"[0-9a-fA-F]{64}", raw) else b64d(raw)
    if len(seed) != 32:
        die("MANIFESTS_SIGNING_KEY must be a 32-byte Ed25519 seed (hex or base64url)")
    from cryptography.hazmat.primitives import serialization

    key = _ed25519().Ed25519PrivateKey.from_private_bytes(seed)
    pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    if b64e(pub) != config()["root"]:
        die("MANIFESTS_SIGNING_KEY does not match the pinned root in registry.json")
    return key


def seal(payload, key):
    data = canonical(payload)
    return data, {"payload": b64e(data), "signature": b64e(key.sign(PREFIX + data))}


# --- Signed objects -----------------------------------------------------------


def read_index(catalog):
    path = REPO / CATALOGS[catalog][0]
    if not path.exists():
        return None, None
    env = json.loads(path.read_text())
    return env, json.loads(b64d(env["payload"]))


def bundle_path(catalog, digest):
    return REPO / CATALOGS[catalog][1] / f"{digest}.json"


def bundle_payload(catalog, digest):
    wrapper = json.loads(bundle_path(catalog, digest).read_text())
    return json.loads(b64d(wrapper["envelope"]["payload"]))


def signed_state():
    """id -> {catalog, entry, payload, expires} for every application in a signed index."""
    state, order = {}, {}
    for catalog in CATALOGS:
        _, index = read_index(catalog)
        order[catalog] = []
        for entry in (index or {}).get("entries", []):
            payload = bundle_payload(catalog, entry["digest"])
            state[entry["id"]] = {"catalog": catalog, "entry": entry, "payload": payload}
            order[catalog].append(entry["id"])
    return state, order


# --- Sources ------------------------------------------------------------------


def parse_front_matter(text):
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        raise ValueError("MANIFEST.md must start with a --- front matter block")
    meta = {}
    for i, line in enumerate(lines[1:], 1):
        if line == "---":
            return meta, "\n".join(lines[i + 1 :])
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"front matter line {i + 1} is not `key: value`")
        try:
            meta[key.strip()] = json.loads(value.strip())
        except json.JSONDecodeError:
            raise ValueError(f"front matter `{key.strip()}` must be a JSON value, e.g. \"text\"")
    raise ValueError("front matter block is not closed with ---")


def front_matter(listing):
    keys = ["title", "catalog"] + (["logo"] if listing.get("logo") else [])
    return "---\n" + "".join(f"{k}: {json.dumps(listing[k], ensure_ascii=False)}\n" for k in keys) + "---\n"


def load_app(app_id):
    folder = APPS / app_id
    payload = json.loads((folder / "manifest.json").read_text())
    listing, body = parse_front_matter((folder / "MANIFEST.md").read_text())
    return payload, listing, body


def app_ids():
    return sorted(p.name for p in APPS.iterdir() if p.is_dir()) if APPS.exists() else []


def write_app(app_id, payload, listing, signed):
    folder = APPS / app_id
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "manifest.json").write_text(pretty(payload))
    (folder / "MANIFEST.md").write_text(front_matter(listing) + render(app_id, payload, listing, signed))


# --- Derivations --------------------------------------------------------------


def _escape(segment):
    return segment.replace("~", "~0").replace("/", "~1")


def openapi_graph(app_id, document):
    """The application -> operation graph, plus schema nodes, of an OpenAPI or Swagger document."""
    nodes, edges = [{"id": app_id, "kind": "application"}], []
    for path, item in (document.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for method in METHODS:
            op = item.get(method)
            if not isinstance(op, dict):
                continue
            op_id = f"operation:{method}:{path}"
            nodes.append(
                {
                    "deprecated": bool(op.get("deprecated", False)),
                    "id": op_id,
                    "kind": "operation",
                    "method": method,
                    "name": op["operationId"] if "operationId" in op else f"{method} {path}",
                    "path": path,
                    "pointer": f"#/paths/{_escape(path)}/{method}",
                    "security": op.get("security", document.get("security", [])),
                    "summary": op.get("summary"),
                }
            )
            edges.append({"from": app_id, "kind": "EXPOSES", "to": op_id})
    schemas = (document.get("components") or {}).get("schemas") or document.get("definitions") or {}
    nodes += [{"id": f"schema:{name}", "kind": "schema", "name": name} for name in schemas]
    return {"edges": edges, "nodes": nodes}


def _sorted_graph(graph):
    return (
        sorted(canonical(n) for n in graph.get("nodes", [])),
        sorted(canonical(e) for e in graph.get("edges", [])),
    )


def index_entry(app_id, payload, listing, digest):
    entry = {
        "digest": digest,
        "id": app_id,
        "protocol": payload["protocol"],
        "title": listing["title"],
        "version": payload["version"],
    }
    if listing.get("logo"):
        entry["logo"] = listing["logo"]
    if listing["catalog"] == "drafts":
        entry["readiness"] = payload["readiness"]
        entry["setup_verification"] = payload["setup_verification"]
    return entry


def pending(app_id, payload, listing, signed, now, refresh):
    """Reasons an application's signed objects differ from its sources (empty when current)."""
    s = signed.get(app_id)
    if not s:
        return ["not signed yet"]
    reasons = []
    if s["payload"] != payload:
        reasons.append("manifest.json changed")
    if s["catalog"] != listing["catalog"]:
        reasons.append(f"moving from {s['catalog']} to {listing['catalog']}")
    if s["entry"] != index_entry(app_id, payload, listing, s["entry"]["digest"]):
        reasons.append("listing changed")
    if s["payload"].get("expires", 0) - now < refresh:
        reasons.append("bundle signature expires soon")
    return reasons


# --- Validation ---------------------------------------------------------------


def _need(errors, cond, msg):
    if not cond:
        errors.append(msg)
    return cond


def _secrets(obj, where, errors):
    if isinstance(obj, dict):
        for k, v in obj.items():
            _secrets(v, f"{where}.{k}", errors)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _secrets(v, f"{where}[{i}]", errors)
    elif isinstance(obj, str) and SECRET_RE.search(obj) and not SECRET_OK.search(obj):
        errors.append(f"{where} looks like a real credential")


def check_app(app_id, payload, listing):
    e = []
    _need(e, ID_RE.match(app_id), "directory name must match [a-z0-9][a-z0-9._-]{0,127}")
    if not _need(e, isinstance(payload, dict), "manifest.json must be a JSON object"):
        return e
    _need(e, payload.get("app", app_id) == app_id, "`app` must equal the directory name")
    _need(e, payload.get("kind", "bundle") == "bundle", "`kind` must be \"bundle\"")
    for k in ("not_before", "expires"):
        _need(e, isinstance(payload.get(k, 0), int), f"`{k}` must be an integer (set by signing)")
    protocol = payload.get("protocol")
    _need(e, protocol in PROTOCOLS, f"`protocol` must be one of {', '.join(PROTOCOLS)}")
    v = payload.get("version")
    _need(e, isinstance(v, str) and 1 <= len(v.encode()) <= 128, "`version` must be 1-128 bytes")
    _need(e, isinstance(payload.get("readiness"), str), "`readiness` is required")
    _need(e, isinstance(payload.get("review_required"), dict), "`review_required` is required")
    prov = payload.get("provenance")
    if _need(e, isinstance(prov, dict), "`provenance` is required"):
        _need(e, isinstance(prov.get("url"), str), "`provenance.url` must name the source definition")
        _need(e, re.fullmatch(r"[0-9a-f]{64}", str(prov.get("sha256"))), "`provenance.sha256` must be hex")

    m = payload.get("manifest")
    document = None
    if _need(e, isinstance(m, dict), "`manifest` is required"):
        _need(e, m.get("apiVersion") == "ragentic.dev/v1", "`manifest.apiVersion` must be ragentic.dev/v1")
        _need(e, m.get("kind") == "ConnectorTemplate", "`manifest.kind` must be ConnectorTemplate")
        _need(e, (m.get("metadata") or {}).get("name") == app_id, "`manifest.metadata.name` must equal the id")
        spec = m.get("spec") or {}
        _need(e, isinstance(spec.get("title"), str), "`manifest.spec.title` is required")
        base = spec.get("base") or {}
        _need(e, base.get("protocol") == protocol, "`manifest.spec.base.protocol` must equal `protocol`")
        specification = base.get("specification") or {}
        document = specification.get("document")
        _need(
            e,
            isinstance(document, dict) or (protocol == "graphql" and isinstance(specification.get("text"), str)),
            "`manifest.spec.base.specification` needs a `document` object (or SDL `text` for GraphQL)",
        )
        if "endpoint" in base:
            _need(e, str(base["endpoint"]).startswith("https://"), "`manifest.spec.base.endpoint` must be https")
        _secrets(base.get("headers", {}), "manifest.spec.base.headers", e)

    graph = payload.get("graph")
    if _need(e, isinstance(graph, dict), "`graph` is required"):
        nodes, edges = graph.get("nodes"), graph.get("edges")
        if _need(e, isinstance(nodes, list) and isinstance(edges, list), "`graph` needs nodes and edges"):
            ids = {n.get("id") for n in nodes if isinstance(n, dict)}
            _need(e, all(isinstance(n, dict) and "id" in n and "kind" in n for n in nodes), "graph nodes need id and kind")
            _need(e, all(x.get("from") in ids and x.get("to") in ids for x in edges), "graph edges must join known nodes")
            if protocol == "openapi" and isinstance(document, dict):
                _need(
                    e,
                    _sorted_graph(graph) == _sorted_graph(openapi_graph(app_id, document)),
                    f"`graph` is out of date; run `python tools/catalog.py graph {app_id}`",
                )

    _need(e, isinstance(listing.get("title"), str) and 1 <= len(listing["title"].encode()) <= 256, "front matter `title` must be 1-256 bytes")
    _need(e, listing.get("catalog") in CATALOGS, "front matter `catalog` must be \"published\" or \"drafts\"")
    if "logo" in listing:
        _need(e, str(listing["logo"]).startswith("https://"), "front matter `logo` must be an https URL")
    _need(e, set(listing) <= {"title", "catalog", "logo"}, "front matter allows only title, catalog and logo")

    if listing.get("catalog") == "drafts":
        _need(e, isinstance(payload.get("setup_verification"), str), "drafts need `setup_verification`")
    if listing.get("catalog") == "published":
        _need(e, payload.get("readiness") not in NOT_CONNECTABLE, "published apps cannot have readiness discovered/preview_only")
        setup = payload.get("setup") or {}
        _need(e, isinstance(setup.get("credential"), dict), "published apps need `setup.credential`")
        _need(e, isinstance(setup.get("probe"), dict), "published apps need a `setup.probe` connection test")
        rights = payload.get("rights") or {}
        _need(e, isinstance(rights.get("source"), dict), "published apps need `rights.source` (license)")
        _need(e, isinstance(rights.get("brand"), dict), "published apps need `rights.brand` (attribution)")
        _need(e, bool((payload.get("a2ui") or {}).get("messages")), "published apps need an `a2ui` setup form")
    for k in ("setup", "a2ui"):
        _secrets(payload.get(k, {}), k, e)
    _need(e, len(canonical(payload)) <= MAX_PAYLOAD, "payload is larger than 16 MiB")
    return e


def check_signed(errors):
    """Verify both indexes, every bundle they name and sources.json against the pinned root."""
    cfg, key = config(), public_key()
    for catalog, (name, directory, kind) in CATALOGS.items():
        env, _ = read_index(catalog)
        if env is None:
            errors.append(f"{name}: missing")
            continue
        try:
            index = json.loads(open_envelope(env, key))
        except ValueError:
            errors.append(f"{name}: signature does not verify against the root in registry.json")
            continue
        if index.get("kind") != kind or index.get("registry") != cfg["registry"]:
            errors.append(f"{name}: wrong kind or registry")
        ids = [x["id"] for x in index["entries"]]
        if len(ids) != len(set(ids)):
            errors.append(f"{name}: duplicate ids")
        named = set()
        for entry in index["entries"]:
            path = bundle_path(catalog, entry["digest"])
            named.add(path.name)
            if not path.exists():
                errors.append(f"{directory}/{path.name}: missing for {entry['id']}")
                continue
            wrapper = json.loads(path.read_text())
            try:
                data = open_envelope(wrapper["envelope"], key)
            except ValueError:
                errors.append(f"{directory}/{path.name}: bad signature")
                continue
            p = json.loads(data)
            if hashlib.sha256(data).hexdigest() != entry["digest"] or wrapper.get("chain") != []:
                errors.append(f"{directory}/{path.name}: digest or chain mismatch")
            if p.get("app") != entry["id"] or p.get("version") != entry["version"]:
                errors.append(f"{directory}/{path.name}: app or version differs from the index")
        stray = {p.name for p in (REPO / directory).glob("*.json")} - named
        errors += [f"{directory}/{n}: not named by {name}" for n in sorted(stray)]


def source_files():
    files = sorted(p for p in APPS.rglob("*") if p.is_file()) + [REPO / "CATALOG.md"]
    return {str(p.relative_to(REPO)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files if p.exists()}


def check_sources():
    """Plain-text files that differ from the signed sources.json (None when it is absent)."""
    path = REPO / "sources.json"
    if not path.exists():
        return None
    data = json.loads(open_envelope(json.loads(path.read_text()), public_key()))
    signed, now = data["files"], source_files()
    return sorted(k for k in set(signed) | set(now) if signed.get(k) != now.get(k))


def cmd_validate(args):
    cfg, now = config(), int(time.time())
    refresh = cfg["refresh_days"] * 86400
    errors = []
    check_signed(errors)
    signed, _ = signed_state()
    waiting, stale_docs = {}, []
    ids = app_ids()
    for app_id in ids:
        folder = APPS / app_id
        extra = {p.name for p in folder.iterdir()} - {"manifest.json", "MANIFEST.md"}
        if extra:
            errors.append(f"apps/{app_id}: unexpected files {sorted(extra)}")
        try:
            payload, listing, body = load_app(app_id)
        except (OSError, ValueError) as exc:
            errors.append(f"apps/{app_id}: {exc}")
            continue
        problems = check_app(app_id, payload, listing)
        errors += [f"apps/{app_id}: {msg}" for msg in problems]
        if problems:
            continue
        if body != render(app_id, payload, listing, signed):
            stale_docs.append(app_id)
        reasons = pending(app_id, payload, listing, signed, now, refresh)
        if reasons:
            waiting[app_id] = reasons
    for app_id in sorted(set(signed) - set(ids)):
        waiting[app_id] = ["removed from apps/; will be unpublished"]
    if (REPO / "CATALOG.md").exists() is False or (REPO / "CATALOG.md").read_text() != render_catalog(signed):
        stale_docs.append("CATALOG.md")
    if stale_docs:
        errors.append(
            f"generated docs are out of date for {', '.join(stale_docs[:10])}"
            f"{' …' if len(stale_docs) > 10 else ''}; run `python tools/catalog.py docs`"
        )
    changed = check_sources()

    print(f"{len(ids)} applications, {len(ids) - len(waiting)} signed and current, {len(waiting)} waiting for signature")
    for app_id, reasons in sorted(waiting.items())[:50]:
        print(f"  pending  {app_id}: {'; '.join(reasons)}")
    if len(waiting) > 50:
        print(f"  … and {len(waiting) - 50} more")
    if changed is None:
        print("sources.json: not signed yet")
    elif changed:
        print(f"sources.json: {len(changed)} plain-text files changed since signing")
    if args.require_signed:
        if waiting:
            errors.append(f"{len(waiting)} applications are not signed")
        if changed is None or changed:
            errors.append("sources.json does not cover the current plain-text files")
    for msg in errors:
        print(f"ERROR {msg}")
    if errors:
        sys.exit(1)
    print("ok")


# --- Signing ------------------------------------------------------------------


def cmd_sign(args):
    cfg, now = config(), int(time.time())
    validity, refresh = cfg["validity_days"] * 86400, cfg["refresh_days"] * 86400
    key = None if args.dry_run else signing_key()
    signed, order = signed_state()
    ids = app_ids()
    plan, entries = {}, {c: {} for c in CATALOGS}

    for app_id in ids:
        payload, listing, _ = load_app(app_id)
        errs = check_app(app_id, payload, listing)
        if errs:
            die(f"apps/{app_id}: {errs[0]} (run validate)")
        catalog, s = listing["catalog"], signed.get(app_id)
        reasons = pending(app_id, payload, listing, signed, now, refresh)
        if s and s["payload"] == payload and s["payload"].get("expires", 0) - now >= refresh:
            digest = s["entry"]["digest"]  # same bytes; at most a listing change or a move
            if s["catalog"] != catalog and not args.dry_run:
                src = bundle_path(s["catalog"], digest)
                dst = bundle_path(catalog, digest)
                dst.parent.mkdir(exist_ok=True)
                dst.write_bytes(src.read_bytes())
        else:
            payload = dict(payload, kind="bundle", app=app_id, not_before=now, expires=now + validity)
            if args.dry_run:
                digest = "0" * 64
            else:
                data, env = seal(payload, key)
                digest = hashlib.sha256(data).hexdigest()
                path = bundle_path(catalog, digest)
                path.parent.mkdir(exist_ok=True)
                path.write_text(compact({"chain": [], "envelope": env}))
                (APPS / app_id / "manifest.json").write_text(pretty(payload))
        if reasons:
            plan[app_id] = reasons
        entries[catalog][app_id] = index_entry(app_id, payload, listing, digest)

    removed = sorted(set(signed) - set(ids))
    changed_catalogs = []
    for catalog, (name, directory, kind) in CATALOGS.items():
        _, index = read_index(catalog)
        keep = [i for i in order[catalog] if i in entries[catalog]]
        new = keep + sorted(set(entries[catalog]) - set(keep))
        listed = [entries[catalog][i] for i in new]
        expiring = not index or index["expires"] - now < refresh
        if index and index["entries"] == listed and not expiring:
            continue
        changed_catalogs.append(name)
        if args.dry_run:
            continue
        payload = {
            "entries": listed,
            "expires": now + validity,
            "kind": kind,
            "not_before": now,
            "registry": cfg["registry"],
            "sequence": (index or {}).get("sequence", 0) + 1,
        }
        _, env = seal(payload, key)
        (REPO / name).write_text(compact(env))
        live = {e["digest"] + ".json" for e in listed}
        for stale in (REPO / directory).glob("*.json"):
            if stale.name not in live:
                stale.unlink()

    print(f"{len(plan)} applications to sign, {len(removed)} to unpublish, indexes: {', '.join(changed_catalogs) or 'unchanged'}")
    for app_id, reasons in sorted(plan.items())[:50]:
        print(f"  {app_id}: {'; '.join(reasons)}")
    for app_id in removed:
        print(f"  {app_id}: removed")
    if args.dry_run:
        return

    signed, _ = signed_state()
    regenerate_docs(signed)
    files = source_files()
    previous = REPO / "sources.json"
    old = json.loads(b64d(json.loads(previous.read_text())["payload"])) if previous.exists() else {}
    if old.get("files") != files or old.get("expires", 0) - now < refresh:
        _, index = read_index("published")
        _, env = seal(
            {
                "expires": now + validity,
                "files": files,
                "kind": "sources",
                "not_before": now,
                "registry": cfg["registry"],
                "sequence": index["sequence"],
            },
            key,
        )
        previous.write_text(compact(env))
        print(f"sources.json: signed {len(files)} plain-text files")


# --- Docs ---------------------------------------------------------------------


def _cell(value):
    text = "" if value is None else re.sub(r"\s+", " ", str(value))
    return text.replace("\\", "\\\\").replace("|", "\\|").strip() or "—"


def _code(value):
    return f"`{value}`" if value not in (None, "") else "—"


def render(app_id, payload, listing, signed):
    spec = (payload.get("manifest") or {}).get("spec") or {}
    base = spec.get("base") or {}
    prov = payload.get("provenance") or {}
    setup = payload.get("setup") or {}
    rights = payload.get("rights") or {}
    cred, probe = setup.get("credential") or {}, setup.get("probe") or {}
    s = signed.get(app_id)
    current = s and s["payload"] == payload and s["catalog"] == listing["catalog"] and s["entry"] == index_entry(
        app_id, payload, listing, s["entry"]["digest"]
    )
    if current:
        signature = f"`{s['entry']['digest']}` in `{CATALOGS[s['catalog']][1]}/`, expires {iso(payload['expires'])}"
    else:
        signature = "Not signed yet: these sources are waiting for the signing job."
    license_ = prov.get("license") or {}
    source_rights = rights.get("source") or {}
    brand = rights.get("brand") or {}
    credential = cred.get("type")
    if cred.get("header"):
        credential = f"{credential} (`{cred['header']}`{' ' + repr(cred['prefix']) if cred.get('prefix') else ''})"

    out = [
        GENERATED,
        "",
        f"# {listing['title']}",
        "",
        f"`{app_id}` · {payload.get('protocol')} · version {_code(payload.get('version'))} · "
        f"**{listing['catalog']}** · readiness `{payload.get('readiness')}`",
        "",
    ]
    if spec.get("description"):
        out += [_cell(spec["description"]), ""]
    rows = [
        ("Signed bundle", signature),
        ("Endpoint", _code(base.get("endpoint"))),
        ("Credential", credential or "—"),
        ("Connection test", f"{probe.get('method', '')} {_code(probe.get('endpoint'))}".strip() if probe else "—"),
        ("Setup verification", _code(payload.get("setup_verification"))),
        ("Source definition", prov.get("url") or "—"),
        ("Upstream", f"{prov['repository']} @ `{prov.get('commit', '')[:12]}`" if prov.get("repository") else "—"),
        ("Source SHA-256", _code(prov.get("sha256"))),
        ("Source license", source_rights.get("spdx") or license_.get("name") or "—"),
        ("Fetched", prov.get("fetched_at") or "—"),
    ]
    out += ["| | |", "| --- | --- |"] + [f"| {k} | {_cell(v)} |" for k, v in rows] + [""]
    if brand or source_rights.get("copyright_notice"):
        out += ["## Rights", ""]
        if brand.get("attribution"):
            out += [_cell(brand["attribution"]), ""]
        if source_rights.get("copyright_notice"):
            out += [f"Copyright: {_cell(source_rights['copyright_notice'])}", ""]
    review = payload.get("review_required") or {}
    if review:
        out += ["## Review checklist", ""]
        for k, v in sorted(review.items()):
            if isinstance(v, bool):
                out.append(f"- [{' ' if v else 'x'}] {k.replace('_', ' ')}")
            elif v:
                out.append(f"- [ ] {k.replace('_', ' ')}: {', '.join(map(str, v))}")
        out.append("")
    nodes = (payload.get("graph") or {}).get("nodes") or []
    ops = [n for n in nodes if n.get("kind") == "operation"]
    others = {}
    for n in nodes:
        if n.get("kind") not in ("operation", "application"):
            others[n.get("kind")] = others.get(n.get("kind"), 0) + 1
    out += [f"## Operations ({len(ops)})", ""]
    if others:
        out += [", ".join(f"{v} {k} nodes" for k, v in sorted(others.items())) + " in the graph.", ""]
    if ops:
        if all("method" in n and "path" in n for n in ops):
            out += ["| Method | Path | Name | Summary |", "| --- | --- | --- | --- |"]
            out += [
                f"| {n['method'].upper()} | `{_cell(n['path'])}` | {_cell(n.get('name'))} | {_cell(n.get('summary'))} |"
                for n in ops
            ]
        else:
            out += ["| Operation | Name | Summary |", "| --- | --- | --- |"]
            out += [f"| `{_cell(n['id'])}` | {_cell(n.get('name'))} | {_cell(n.get('summary'))} |" for n in ops]
        out.append("")
    return "\n".join(out)


def render_catalog(signed):
    rows = {c: [] for c in CATALOGS}
    for app_id in app_ids():
        payload, listing, _ = load_app(app_id)
        ops = sum(1 for n in (payload.get("graph") or {}).get("nodes", []) if n.get("kind") == "operation")
        status = "signed" if not pending(app_id, payload, listing, signed, 0, 0) else "pending"
        rows[listing["catalog"]].append(
            f"| [{_cell(listing['title'])}](apps/{app_id}/MANIFEST.md) | `{app_id}` | {payload['protocol']} | "
            f"{_cell(payload['version'])} | {ops} | `{payload.get('readiness')}` | {status} |"
        )
    head = ["| Application | Id | Protocol | Version | Operations | Readiness | Signature |", "| --- | --- | --- | --- | --- | --- | --- |"]
    out = [
        "<!-- Generated by tools/catalog.py docs. -->",
        "",
        "# Catalog",
        "",
        f"{sum(map(len, rows.values()))} applications: {len(rows['published'])} published and "
        f"{len(rows['drafts'])} drafts. Drafts can be browsed but not connected until reviewed and published.",
        "",
        f"## Published ({len(rows['published'])})",
        "",
        *head,
        *rows["published"],
        "",
        f"## Drafts ({len(rows['drafts'])})",
        "",
        *head,
        *rows["drafts"],
        "",
    ]
    return "\n".join(out)


def regenerate_docs(signed):
    for app_id in app_ids():
        payload, listing, _ = load_app(app_id)
        (APPS / app_id / "MANIFEST.md").write_text(front_matter(listing) + render(app_id, payload, listing, signed))
    (REPO / "CATALOG.md").write_text(render_catalog(signed))


def cmd_docs(args):
    signed, _ = signed_state()
    regenerate_docs(signed)
    print(f"wrote {len(app_ids())} MANIFEST.md files and CATALOG.md")


