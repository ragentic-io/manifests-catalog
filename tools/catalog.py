def _cell(value):
    text = "" if value is None else re.sub(r"\s+", " ", str(value))
    return text.replace("\\", "\\\\").replace("|", "\\|").strip() or "—"


def _code(value):
    return f"`{value}`" if value not in (None, "") else "—"


def _params(node):
    names = [f"`{_cell(p.get('name'))}`{'*' if p.get('required') else ''}" for p in node.get("parameters", [])]
    if node.get("request"):
        names.append(f"body{'*' if node['request'].get('required') else ''}: {_cell(node['request'].get('type'))}")
    return ", ".join(names) or "—"


def _returns(node):
    ok = [r["type"] for r in node.get("responses", []) if r["status"].startswith("2") and r.get("type")]
    return _cell(", ".join(dict.fromkeys(ok))) if ok else "—"


def render(app_id, payload, listing, signed):
    spec = (payload.get("manifest") or {}).get("spec") or {}
    base = spec.get("base") or {}
    prov = payload.get("provenance") or {}
    setup = payload.get("setup") or {}
    rights = payload.get("rights") or {}
    cred, probe = setup.get("credential") or {}, setup.get("probe") or {}
    s = signed.get(app_id)
    current = s and s["payload"] == payload and s["catalog"] == listing["catalog"] and s["entry"] == index_entry(
        app_id, payload, listing, s["entry"]["digest"]
    )
    if current:
        signature = f"`{s['entry']['digest']}` in `{CATALOGS[s['catalog']][1]}/`, expires {iso(payload['expires'])}"
    else:
        signature = "Not signed yet: these sources are waiting for the signing job."
    license_ = prov.get("license") or {}
    source_rights = rights.get("source") or {}
    brand = rights.get("brand") or {}
    credential = cred.get("type")
    if cred.get("header"):
        credential = f"{credential} (`{cred['header']}`{' ' + repr(cred['prefix']) if cred.get('prefix') else ''})"

    out = [
        GENERATED,
        "",
        f"# {listing['title']}",
        "",
        f"`{app_id}` · {payload.get('protocol')} · version {_code(payload.get('version'))} · "
        f"**{listing['catalog']}** · readiness `{payload.get('readiness')}`",
        "",
    ]
    if spec.get("description"):
        out += [_cell(spec["description"]), ""]
    rows = [
        ("Categories", ", ".join(categories()[c]["title"] for c in listing["categories"])),
        ("Signed bundle", signature),
        ("Endpoint", _code(base.get("endpoint"))),
        ("Credential", credential or "—"),
        ("Connection test", f"{probe.get('method', '')} {_code(probe.get('endpoint'))}".strip() if probe else "—"),
        ("Setup verification", _code(payload.get("setup_verification"))),
        ("Source definition", prov.get("url") or "—"),
        ("Upstream", prov["repository"] + (f" @ `{prov['commit'][:12]}`" if prov.get("commit") else "") if prov.get("repository") else "—"),
        ("Source SHA-256", _code(prov.get("sha256"))),
        ("Source license", source_rights.get("spdx") or license_.get("name") or "—"),
        ("Fetched", prov.get("fetched_at") or "—"),
    ]
    out += ["| | |", "| --- | --- |"] + [f"| {k} | {_cell(v)} |" for k, v in rows] + [""]
    if brand or source_rights.get("copyright_notice"):
        out += ["## Rights", ""]
        if brand.get("attribution"):
            out += [_cell(brand["attribution"]), ""]
        if source_rights.get("copyright_notice"):
            out += [f"Copyright: {_cell(source_rights['copyright_notice'])}", ""]
    review = payload.get("review_required") or {}
    if review:
        out += ["## Review checklist", ""]
        for k, v in sorted(review.items()):
            if isinstance(v, bool):
                out.append(f"- [{' ' if v else 'x'}] {k.replace('_', ' ')}")
            elif v:
                out.append(f"- [ ] {k.replace('_', ' ')}: {', '.join(map(str, v))}")
        out.append("")
    nodes = (payload.get("graph") or {}).get("nodes") or []
    ops = [n for n in nodes if n.get("kind") == "operation"]
    others = {}
    for n in nodes:
        if n.get("kind") not in ("operation", "application"):
            others[n.get("kind")] = others.get(n.get("kind"), 0) + 1
    out += [f"## Operations ({len(ops)})", ""]
    if others:
        out += [", ".join(f"{v} {k} nodes" for k, v in sorted(others.items())) + " in the graph.", ""]
    if ops:
        if all("method" in n and "path" in n for n in ops):
            out += [
                "Parameters marked * are required. Safe operations only read, so a preview may call them.",
                "",
                "| Method | Path | Name | Parameters | Returns | Safe | Summary |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
            out += [
                f"| {n['method'].upper()} | `{_cell(n['path'])}` | {_cell(n.get('name'))} | {_params(n)} | "
                f"{_returns(n)} | {'yes' if n.get('safe') else ''} | {_cell(n.get('summary'))} |"
                for n in ops
            ]
        else:
            out += ["| Operation | Name | Summary |", "| --- | --- | --- |"]
            out += [f"| `{_cell(n['id'])}` | {_cell(n.get('name'))} | {_cell(n.get('summary'))} |" for n in ops]
        out.append("")
    return "\n".join(out)


def render_catalog(signed):
    rows = {c: [] for c in CATALOGS}
    known = categories()
    by_category = {c: {k: 0 for k in CATALOGS} for c in known}
    for app_id in app_ids():
        payload, listing, _ = load_app(app_id)
        ops = sum(1 for n in (payload.get("graph") or {}).get("nodes", []) if n.get("kind") == "operation")
        status = "signed" if not pending(app_id, payload, listing, signed, 0, 0) else "pending"
        for c in listing["categories"]:
            by_category[c][listing["catalog"]] += 1
        rows[listing["catalog"]].append(
            f"| [{_cell(listing['title'])}](apps/{app_id}/MANIFEST.md) | `{app_id}` | "
            f"{', '.join(listing['categories'])} | {payload['protocol']} | "
            f"{_cell(payload['version'])} | {ops} | `{payload.get('readiness')}` | {status} |"
        )
    head = [
        "| Application | Id | Categories | Protocol | Version | Operations | Readiness | Signature |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    category_rows = [
        f"| `{c}` | {_cell(known[c]['title'])} | {n['published']} | {n['drafts']} |" for c, n in by_category.items()
    ]
    out = [
        "<!-- Generated by tools/catalog.py docs. -->",
        "",
        "# Catalog",
        "",
        f"{sum(map(len, rows.values()))} applications: {len(rows['published'])} published and "
        f"{len(rows['drafts'])} drafts. Drafts can be browsed but not connected until reviewed and published.",
        "",
        "## Categories",
        "",
        "An application can have up to four categories. They are defined in [categories.json](categories.json).",
        "",
        "| Id | Category | Published | Drafts |",
        "| --- | --- | --- | --- |",
        *category_rows,
        "",
        f"## Published ({len(rows['published'])})",
        "",
        *head,
        *rows["published"],
        "",
        f"## Drafts ({len(rows['drafts'])})",
        "",
        *head,
        *rows["drafts"],
        "",
    ]
    return "\n".join(out)


def regenerate_docs(signed):
    for app_id in app_ids():
        payload, listing, _ = load_app(app_id)
        (APPS / app_id / "MANIFEST.md").write_text(front_matter(listing) + render(app_id, payload, listing, signed))
    (REPO / "CATALOG.md").write_text(render_catalog(signed))


def cmd_docs(args):
    signed, _ = signed_state()
    regenerate_docs(signed)
    print(f"wrote {len(app_ids())} MANIFEST.md files and CATALOG.md")


